class TestNoForceFlag:
    """The commit/push functions must never use a force flag of any kind.

    The spec requires that '--force' and 'force=True' do not appear anywhere
    in the routing module source.  The only allowed force-related token is
    'force=False' (the explicit non-force flag in the GitHub PATCH payload).
    """

    def _routing_source(self) -> str:
        return inspect.getsource(routing)

    def test_no_force_shell_flag(self):
        src = self._routing_source()
        assert "--force" not in src, (
            'routing.py must not contain "--force". Found in source.'
        )

    def test_no_force_true_kwarg(self):
        src = self._routing_source()
        # 'force=False' is intentional (non-force API call) — only 'force=True' is banned.
        assert "force=True" not in src, (
            'routing.py must not contain "force=True". Found in source.'
        )

    def test_gate_atomic_push_uses_force_false(self):
        """The atomic push gate should explicitly set force=False in the payload."""
        src = inspect.getsource(routing.gate_atomic_push)
        assert "force" in src.lower(), (
            "gate_atomic_push should include force=False in the payload."
        )
