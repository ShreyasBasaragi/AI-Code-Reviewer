def _make_groq_response(text: str):
    """Build a minimal mock Groq completion response."""
    msg = MagicMock()
    msg.content = text
    choice = MagicMock()
    choice.message = msg
    resp = MagicMock()
    resp.choices = [choice]
    return resp


class TestClassifyWithGroq:
    """classify_with_groq must map any non-'easy' response to 'hard'."""

    def _call(self, groq_reply: str, env_key: str = "fake-key") -> str:
        with patch.dict(os.environ, {"GROQ_API_KEY": env_key}):
            with patch("mcp_server.routing.Groq") as MockGroq:
                instance = MockGroq.return_value
                instance.chat.completions.create.return_value = _make_groq_response(groq_reply)
                return routing.classify_with_groq("def foo(): pass", "some comment")

    def test_exact_easy_lowercase(self):
        assert self._call("easy") == "easy"

    def test_easy_with_period_is_hard(self):
        # "Easy." is NOT exactly "easy" after strip+lower → hard
        assert self._call("Easy.") == "hard"

    def test_hard_lowercase(self):
        assert self._call("hard") == "hard"

    def test_garbage_text_is_hard(self):
        assert self._call("I think this is easy or hard") == "hard"

    def test_empty_response_is_hard(self):
        assert self._call("") == "hard"

    def test_no_api_key_returns_hard(self):
        env = {k: v for k, v in os.environ.items() if k != "GROQ_API_KEY"}
        with patch.dict(os.environ, env, clear=True):
            result = routing.classify_with_groq("code", "comment")
        assert result == "hard"

    def test_api_exception_returns_hard(self):
        with patch.dict(os.environ, {"GROQ_API_KEY": "fake"}):
            with patch("mcp_server.routing.Groq") as MockGroq:
                instance = MockGroq.return_value
                instance.chat.completions.create.side_effect = RuntimeError("network")
                result = routing.classify_with_groq("code", "comment")
        assert result == "hard"


