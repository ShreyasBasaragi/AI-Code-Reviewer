class TestParseModelOutput:
    def test_well_formed_output(self):
        raw = (
            "The variable `x` is undefined before use.\n\n"
            "```python\n"
            "x = 0\n"
            "print(x)\n"
            "```"
        )
        comment, code = routing.parse_model_output(raw)
        assert "undefined" in comment
        assert "x = 0" in code

    def test_missing_code_block_returns_full_text_as_comment(self):
        raw = "No code block here, just a comment about the issue."
        comment, code = routing.parse_model_output(raw)
        assert comment == raw.strip()
        assert code == ""

    def test_empty_string_returns_empty_tuple(self):
        comment, code = routing.parse_model_output("")
        assert comment == ""
        assert code == ""

    def test_whitespace_only_returns_empty_tuple(self):
        comment, code = routing.parse_model_output("   \n   ")
        assert comment == ""
        assert code == ""

    def test_only_code_block_no_preceding_comment(self):
        raw = "```python\nreturn x + 1\n```"
        comment, code = routing.parse_model_output(raw)
        # code block should be parsed; comment may be empty or trailing text
        assert "return x + 1" in code


