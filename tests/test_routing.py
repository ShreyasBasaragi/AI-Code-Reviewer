        with patch("mcp_server.routing.requests") as mock_req:
            mock_req.get.side_effect = [pr_ref, cand_ref, commit_resp]
            mock_req.patch.return_value = patch_resp
            # Also patch hmac_attest.verify_patch so no env var needed
            with patch("mcp_server.routing.hmac_attest") as mock_hmac:
                mock_hmac.extract_token_from_commit_message.return_value = None
                mock_hmac.verify_patch.return_value = (True, "HMAC attestation skipped")
