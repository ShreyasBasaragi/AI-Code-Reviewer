def _make_route_hunk_kwargs(**overrides):
    """Return a minimal valid keyword dict for route_hunk."""
    base = dict(
        hunk_id="hunk-001",
        hunk_patch="+x = 1\n",
        file_path="src/foo.py",
        original_code="x = 2",
        patched_code="x = 1",
        pr_number=7,
        pr_branch="feature",
        original_head_sha="origsha",
        commit_id="commitabc",
        owner="owner",
        repo="repo",
        line_start=10,
        line_end=10,
        github_token="fake-tok",
        ci_timeout_seconds=1,
    )
    base.update(overrides)
    return base


class TestRouting:
    """Integration-level tests that mock every external call."""

    def test_hard_label_never_reaches_commit_path(self):
        """A hard Groq label must result in a suggestion, never a commit."""
        with patch.object(routing, "classify_with_groq", return_value="hard"):
            with patch.object(routing, "post_suggestion_comment", return_value=True) as mock_post:
                with patch.object(routing, "gate_blast_radius") as mock_g1:
                    result = routing.route_hunk(**_make_route_hunk_kwargs())

        # Groq said hard → suggestion posted, gates never evaluated
        mock_post.assert_called_once()
        mock_g1.assert_not_called()
        assert result["final_action"] in ("suggestion_posted", "suggestion_failed")
        assert result["groq_label"] == "hard"

    def test_easy_label_that_fails_g3_is_downgraded_to_suggestion(self):
        """An easy Groq label + G3 failure must downgrade to suggestion path."""
        with patch.object(routing, "classify_with_groq", return_value="easy"):
            with patch.object(routing, "gate_blast_radius", return_value=(True, "ok")):
                with patch.object(routing, "gate_protected_paths", return_value=(True, "ok")):
                    with patch.object(
                        routing,
                        "gate_linter",
                        return_value=(False, "G3 linter: patch does not remove any lint errors"),
                    ):
                        with patch.object(
                            routing, "post_suggestion_comment", return_value=True
                        ) as mock_post:
                            with patch.object(routing, "gate_staging") as mock_g4:
                                result = routing.route_hunk(**_make_route_hunk_kwargs())

        # Must have downgraded
        mock_post.assert_called_once()
        mock_g4.assert_not_called()  # G4 should not run if G3 fails
        assert "downgraded" in result["final_action"]
        assert result["gate_results"]["G3"]["passed"] is False

    def test_all_gates_pass_commits(self):
        """When easy + all 6 gates pass, final_action is 'committed'."""
        with patch.object(routing, "classify_with_groq", return_value="easy"):
            with patch.object(routing, "gate_blast_radius", return_value=(True, "ok")):
                with patch.object(routing, "gate_protected_paths", return_value=(True, "ok")):
                    with patch.object(routing, "gate_linter", return_value=(True, "ok")):
                        with patch.object(
                            routing,
                            "gate_staging",
                            return_value=(True, "ok", "candidate-7-abc1234"),
                        ):
                            with patch.object(routing, "gate_ci", return_value=(True, "ok")):
                                with patch.object(
                                    routing, "gate_atomic_push", return_value=(True, "ok")
                                ):
                                    with patch.object(
                                        routing, "cleanup_candidate_branch"
                                    ) as mock_cleanup:
                                        result = routing.route_hunk(
                                            **_make_route_hunk_kwargs()
                                        )

        assert result["final_action"] == "committed"
        # Cleanup must always be called
        mock_cleanup.assert_called_once_with(
            "owner", "repo", "candidate-7-abc1234", "fake-tok"
        )

    def test_cleanup_called_even_when_g5_fails(self):
        """Candidate branch must be cleaned up even if CI fails."""
        with patch.object(routing, "classify_with_groq", return_value="easy"):
            with patch.object(routing, "gate_blast_radius", return_value=(True, "ok")):
                with patch.object(routing, "gate_protected_paths", return_value=(True, "ok")):
                    with patch.object(routing, "gate_linter", return_value=(True, "ok")):
                        with patch.object(
                            routing,
                            "gate_staging",
                            return_value=(True, "ok", "candidate-7-xxxxxyz"),
                        ):
                            with patch.object(
                                routing, "gate_ci", return_value=(False, "G5: timeout")
                            ):
                                with patch.object(
                                    routing, "post_suggestion_comment", return_value=True
                                ):
                                    with patch.object(
                                        routing, "cleanup_candidate_branch"
                                    ) as mock_cleanup:
                                        routing.route_hunk(**_make_route_hunk_kwargs())

        mock_cleanup.assert_called_once()


