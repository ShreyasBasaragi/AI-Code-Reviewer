class TestGateBlastRadius:
    def test_pass_within_limit(self):
        patch_text = "+x = 1\n-y = 2\n+z = 3\n context\n"
        passed, reason = routing.gate_blast_radius(patch_text, "foo.py")
        assert passed is True

    def test_fail_exceeds_limit(self):
        # 4 changed lines > 3
        patch_text = "+a = 1\n+b = 2\n+c = 3\n+d = 4\n"
        passed, reason = routing.gate_blast_radius(patch_text, "foo.py")
        assert passed is False
        assert "4" in reason

    def test_header_lines_excluded(self):
        # +++ and --- lines must NOT be counted
        patch_text = "--- a/foo.py\n+++ b/foo.py\n+x = 1\n"
        passed, reason = routing.gate_blast_radius(patch_text, "foo.py")
        assert passed is True

    def test_zero_changed_lines_passes(self):
        patch_text = " context line only\n"
        passed, _ = routing.gate_blast_radius(patch_text, "foo.py")
        assert passed is True


